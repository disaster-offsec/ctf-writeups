package main

import (
	"bufio"
	"encoding/base64"
	"fmt"
	"net"
	"os"
	"strings"
	"time"
)

// --- НАЧАЛО БЛОКА ГЕНЕРАЦИИ (ИЗ ПРЕДЫДУЩЕГО КОДА) ---

const (
	markLiteral = `"\x00"`
	head = "# Zero Report - canonical wrapper (generated by pack.py).\n" +
		"# Edit only the body of generate().\n" +
		"import hashlib\n" +
		"\n" +
		"P = 2 ** 127 - 1\n" +
		"\n" +
		"\n" +
		"def H(source):\n" +
		"    return int.from_bytes(hashlib.sha256(source.encode(\"utf-8\")).digest(), \"big\") % P\n" +
		"\n" +
		"\n"
	genHead = "def generate():\n"
	genTail = "\nif __name__ == \"__main__\":\n    print(generate())\n"
)

func pack(body string) string {
	body = strings.TrimRight(body, "\n")
	if strings.Contains(body, "\x00") {
		panic("body contains MARK")
	}
	if body == "" {
		panic("empty body")
	}

	selfPart := "_x = \x00\nSOURCE = _x.replace(" + markLiteral + ", repr(_x))\n\n"

	var sb strings.Builder
	for _, line := range strings.Split(body, "\n") {
		if line != "" {
			sb.WriteString("    " + line + "\n")
		} else {
			sb.WriteString("\n")
		}
	}
	indentedBody := sb.String()

	v := head + selfPart + genHead + indentedBody + genTail

	// pythonRepr(v)
	var reprSb strings.Builder
	reprSb.WriteString("'")
	for _, r := range v {
		switch r {
		case '\\':
			reprSb.WriteString("\\\\")
		case '\'':
			reprSb.WriteString("\\'")
		case '\n':
			reprSb.WriteString("\\n")
		case '\r':
			reprSb.WriteString("\\r")
		case '\t':
			reprSb.WriteString("\\t")
		case 0:
			reprSb.WriteString("\\x00")
		default:
			if r < 32 || r >= 127 {
				reprSb.WriteString(fmt.Sprintf("\\x%02x", r))
			} else {
				reprSb.WriteRune(r)
			}
		}
	}
	reprSb.WriteString("'")
	reprV := reprSb.String()

	source := strings.ReplaceAll(v, "\x00", reprV)
	if strings.Contains(source, "\x00") {
		panic("MARK survived")
	}
	return source
}

// --- КОНЕЦ БЛОКА ГЕНЕРАЦИИ ---

const (
	host = "solarctf.ru"
	port = "30102"
)

func main() {
	// 1. Генерируем payload
	body := "h = H(SOURCE)\nreturn [h, (h - 1) % P]"
	source := pack(body)
	payload := base64.StdEncoding.EncodeToString([]byte(source))

	// 2. Подключаемся
	conn, err := net.DialTimeout("tcp", host+":"+port, 30*time.Second)
	if err != nil {
		fmt.Fprintf(os.Stderr, "dial error: %v\n", err)
		os.Exit(1)
	}
	defer conn.Close()

	// Ставим дедлайн на всё взаимодействие
	conn.SetDeadline(time.Now().Add(30 * time.Second))

	reader := bufio.NewReader(conn)

	// 3. Читаем баннер до "> "
	var banner strings.Builder
	for {
		b, err := reader.ReadByte()
		if err != nil {
			fmt.Fprintf(os.Stderr, "read banner error: %v\n", err)
			os.Exit(1)
		}
		banner.WriteByte(b)
		if strings.HasSuffix(banner.String(), "> ") {
			break
		}
	}
	fmt.Print(banner.String())

	// 4. Отправляем payload
	_, err = conn.Write([]byte(payload + "\n"))
	if err != nil {
		fmt.Fprintf(os.Stderr, "send error: %v\n", err)
		os.Exit(1)
	}

	// 5. Читаем ответ до закрытия соединения
	resp, err := bufio.NewReader(conn).ReadString('\n')
	if err != nil && err.Error() != "EOF" {
		fmt.Fprintf(os.Stderr, "read response error: %v\n", err)
	}
	fmt.Print("\nRESPONSE: ", resp)
}
